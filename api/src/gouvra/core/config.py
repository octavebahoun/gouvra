"""Application settings, loaded from the environment and validated at startup."""

from __future__ import annotations

import base64
import binascii
from enum import StrEnum
from functools import lru_cache
from typing import Annotated, Literal, Self

from pydantic import Field, SecretStr, field_validator, model_validator
from pydantic_settings import BaseSettings, NoDecode, SettingsConfigDict


class Environment(StrEnum):
    DEVELOPMENT = "development"
    TEST = "test"
    PRODUCTION = "production"


class EmailProvider(StrEnum):
    RESEND = "resend"
    SMTP = "smtp"
    CONSOLE = "console"


class BillingProviderKind(StrEnum):
    NONE = "none"
    SIMULATED = "simulated"
    STRIPE = "stripe"


MIN_SECRET_BYTES = 32


def _decode_key(raw: str) -> bytes:
    try:
        return base64.urlsafe_b64decode(raw + "=" * (-len(raw) % 4))
    except (binascii.Error, ValueError) as exc:
        raise ValueError("must be url-safe base64") from exc


class Settings(BaseSettings):
    """All runtime configuration. Every secret is a `SecretStr` so it never ends up in logs."""

    model_config = SettingsConfigDict(
        env_file=(".env", "../.env"), env_file_encoding="utf-8", extra="ignore"
    )

    app_env: Environment = Environment.DEVELOPMENT
    app_name: str = "Gouvra"
    app_version: str = "0.1.0"
    # Public URL of the web application (used in e-mails, post-login redirects, Origin checks).
    app_url: str = "http://localhost:8080"
    # Public URL where the API itself is reachable. OAuth callbacks are registered on it:
    # http://localhost:8000 in development, usually equal to APP_URL behind the proxy in production.
    api_public_url: str = "http://localhost:8000"
    log_level: str = "INFO"
    log_format: str = "json"  # json | console

    database_url: SecretStr = SecretStr("postgresql+asyncpg://gouvra:gouvra@localhost:5432/gouvra")
    database_pool_size: int = 10
    redis_url: SecretStr = SecretStr("redis://localhost:6379/0")

    # Secrets generated by scripts/gen-secrets
    session_secret: SecretStr = SecretStr("")
    # Key ring "kid:base64key,kid2:base64key" — the first key encrypts, all keys decrypt.
    encryption_keys: SecretStr = SecretStr("")

    # Cookies & sessions
    cookie_secure: bool = True
    session_idle_hours: int = 72
    session_absolute_days: int = 30
    session_rotation_hours: int = 12

    # E-mail
    email_provider: EmailProvider = EmailProvider.CONSOLE
    email_from: str = "Gouvra <no-reply@localhost>"
    resend_api_key: SecretStr = SecretStr("")
    smtp_host: str = "localhost"
    smtp_port: int = 1025
    smtp_username: str = ""
    smtp_password: SecretStr = SecretStr("")
    # none (local relay such as Mailpit) | starttls (port 587) | ssl (implicit TLS, port 465)
    smtp_security: Literal["none", "starttls", "ssl"] = "none"

    # Model providers used by tests and the demo seed (workspaces store their own keys).
    deepseek_api_key: SecretStr = SecretStr("")
    anthropic_api_key: SecretStr = SecretStr("")

    # OAuth (optional)
    github_client_id: str = ""
    github_client_secret: SecretStr = SecretStr("")
    google_client_id: str = ""
    google_client_secret: SecretStr = SecretStr("")

    # Billing
    billing_provider: BillingProviderKind = BillingProviderKind.NONE
    stripe_secret_key: SecretStr = SecretStr("")
    stripe_publishable_key: str = ""
    stripe_webhook_secret: SecretStr = SecretStr("")

    # Sign-up policy
    signup_enabled: bool = True

    # Outbound network policy (SSRF protection). Enable only on trusted self-hosted setups,
    # e.g. to reach a local Ollama server or an internal API from an HTTP tool.
    provider_allow_private_networks: bool = False
    http_tool_allow_private_networks: bool = False

    # Sandbox service (untrusted code tools)
    sandbox_url: str = "http://sandbox:8090"
    sandbox_token: SecretStr = SecretStr("")

    # Limits
    max_request_body_bytes: int = 1_048_576
    max_execution_input_bytes: int = 262_144
    default_execution_timeout_s: int = 120
    max_execution_timeout_s: int = 900
    default_workspace_concurrency: int = 5
    worker_concurrency: int = 16

    # Reverse-proxy hops whose X-Forwarded-For we trust (Caddy in front of the API).
    trusted_proxy_hops: int = 1

    cors_origins: Annotated[list[str], NoDecode] = Field(default_factory=list)

    @field_validator("cors_origins", mode="before")
    @classmethod
    def _split_origins(cls, value: object) -> object:
        if isinstance(value, str):
            return [item.strip() for item in value.split(",") if item.strip()]
        return value

    @field_validator("app_url", "api_public_url")
    @classmethod
    def _strip_slash(cls, value: str) -> str:
        return value.rstrip("/")

    @model_validator(mode="after")
    def _check_production(self) -> Self:
        if self.app_env is Environment.PRODUCTION:
            problems: list[str] = []
            if not self.cookie_secure:
                problems.append("COOKIE_SECURE must be true")
            if self.email_provider is EmailProvider.CONSOLE:
                problems.append("EMAIL_PROVIDER must not be 'console'")
            if (
                self.email_provider is EmailProvider.RESEND
                and not self.resend_api_key.get_secret_value()
            ):
                problems.append("EMAIL_PROVIDER=resend requires RESEND_API_KEY")
            if self.email_provider is EmailProvider.SMTP and self.smtp_security == "none":
                problems.append("SMTP_SECURITY must be 'starttls' or 'ssl'")
            if not self.app_url.startswith("https://"):
                problems.append("APP_URL must use https://")
            if problems:
                raise ValueError("Unsafe production configuration: " + "; ".join(problems))
        if self.app_env is not Environment.TEST:
            if len(self.session_secret.get_secret_value()) < MIN_SECRET_BYTES:
                raise ValueError("SESSION_SECRET is missing or too short — run scripts/gen-secrets")
            if not self.encryption_keys.get_secret_value():
                raise ValueError("ENCRYPTION_KEYS is missing — run scripts/gen-secrets")
        if self.encryption_keys.get_secret_value():
            self.encryption_key_ring()  # validates format eagerly
        if self.billing_provider is BillingProviderKind.STRIPE and not (
            self.stripe_secret_key.get_secret_value()
        ):
            raise ValueError("BILLING_PROVIDER=stripe requires STRIPE_SECRET_KEY")
        return self

    def encryption_key_ring(self) -> list[tuple[str, bytes]]:
        ring: list[tuple[str, bytes]] = []
        for entry in self.encryption_keys.get_secret_value().split(","):
            kid, sep, raw = entry.strip().partition(":")
            if not sep or not kid or not raw:
                raise ValueError("ENCRYPTION_KEYS entries must look like 'kid:base64key'")
            key = _decode_key(raw)
            if len(key) != MIN_SECRET_BYTES:
                raise ValueError(f"encryption key {kid!r} must be 32 bytes")
            ring.append((kid, key))
        return ring

    @property
    def is_production(self) -> bool:
        return self.app_env is Environment.PRODUCTION

    @property
    def is_test(self) -> bool:
        return self.app_env is Environment.TEST

    @property
    def oauth_providers(self) -> list[str]:
        enabled: list[str] = []
        if self.github_client_id and self.github_client_secret.get_secret_value():
            enabled.append("github")
        if self.google_client_id and self.google_client_secret.get_secret_value():
            enabled.append("google")
        return enabled


@lru_cache
def get_settings() -> Settings:
    return Settings()
